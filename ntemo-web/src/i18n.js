const savedLang = (() => {
  try {
    const saved = localStorage.getItem("ntemo_company_settings");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (parsed.language && ["fr", "en", "ru"].includes(parsed.language)) {
        return parsed.language;
      }
    }
  } catch (_) {}
  return "fr";
})();

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang,
  fallbackLng: "fr",
  interpolation: {
    escapeValue: false
  }
});

export default i18n;
